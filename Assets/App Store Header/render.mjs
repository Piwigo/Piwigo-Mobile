#!/usr/bin/env node
// Renders header.html into the App Store product page header video (3840 × 1646, 21:9).
//
// Needs only Node ≥ 22, Google Chrome and Xcode (no npm packages, no ffmpeg):
// Chrome is driven over the DevTools pipe, frames are encoded by encode.swift (AVFoundation).
//
//   node render.mjs                        → header.mov (H.264, 30 fps, one 20 s loop)
//   node render.mjs --codec prores         → ProRes 422 HQ master
//   node render.mjs --fps 60 --codec hevc --out header-60.mov
//   node render.mjs --still 0 --still 3.6  → still-0.png, still-3.6.png (poster frame, checks)
//   node render.mjs --prepare              → rebuilds photos/ + photos.js from ../Images - *
//
// Other options: --frames N (render only the first N frames), --chrome <path>.

import { spawn, execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const WIDTH = 3840, HEIGHT = 1646;
// Eddy's own photos of Delft, free to use in App Store assets.
const PHOTO_DIRS = ['Images - Delft'];

// ---- Arguments --------------------------------------------------------------
const opts = { fps: 30, codec: 'h264', out: null, stills: [], frames: Infinity, prepare: false,
               chrome: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' };
const argv = process.argv.slice(2);
for (let i = 0; i < argv.length; i++) {
  const a = argv[i], v = () => argv[++i];
  switch (a) {
    case '--fps': opts.fps = parseInt(v(), 10); break;
    case '--codec': opts.codec = v(); break;
    case '--out': opts.out = path.resolve(v()); break;
    case '--still': opts.stills.push(parseFloat(v())); break;
    case '--frames': opts.frames = parseInt(v(), 10); break;
    case '--prepare': opts.prepare = true; break;
    case '--chrome': opts.chrome = v(); break;
    default: console.error(`Unknown option ${a}`); process.exit(2);
  }
}
if (![30, 60].includes(opts.fps)) { console.error('Apple accepts 30 or 60 fps.'); process.exit(2); }
if (!['h264', 'hevc', 'prores'].includes(opts.codec)) { console.error('--codec h264|hevc|prores'); process.exit(2); }
opts.out ??= path.join(HERE, 'header.mov');

// ---- Photos -----------------------------------------------------------------
function preparePhotos() {
  const dir = path.join(HERE, 'photos');
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir);
  const list = [];
  for (const sub of PHOTO_DIRS) {
    const src = path.join(HERE, '..', sub);
    for (const name of fs.readdirSync(src).filter(n => /\.jpe?g$/i.test(n)).sort()) {
      const out = `p${String(list.length + 1).padStart(3, '0')}.jpg`;
      execFileSync('sips', ['-Z', '1200', '-s', 'format', 'jpeg', '-s', 'formatOptions', '85',
                            path.join(src, name), '--out', path.join(dir, out)], { stdio: 'ignore' });
      list.push({ src: `photos/${out}`, from: `${sub}/${name}` });
    }
  }
  fs.writeFileSync(path.join(HERE, 'photos.js'),
    '// Generated by render.mjs --prepare: thumbnails of the Assets/Images - * photos.\n' +
    `window.PHOTOS = ${JSON.stringify(list.map(p => p.src))};\n` +
    `// Sources:\n${list.map(p => `//   ${p.src} ← ${p.from}`).join('\n')}\n`);
  console.log(`Prepared ${list.length} photos.`);
}
if (opts.prepare || !fs.existsSync(path.join(HERE, 'photos.js'))) preparePhotos();

// ---- Encoder ----------------------------------------------------------------
function encoderBinary() {
  const src = path.join(HERE, 'encode.swift');
  const bin = path.join(os.tmpdir(), 'piwigo-header-encode');
  if (!fs.existsSync(bin) || fs.statSync(bin).mtimeMs < fs.statSync(src).mtimeMs) {
    console.log('Compiling encode.swift…');
    execFileSync('xcrun', ['swiftc', '-O', src, '-o', bin], { stdio: 'inherit' });
  }
  return bin;
}

// ---- Chrome DevTools over pipe ---------------------------------------------
function launchChrome() {
  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'piwigo-header-chrome-'));
  const proc = spawn(opts.chrome, [
    '--headless=new', '--remote-debugging-pipe', `--user-data-dir=${profile}`,
    '--no-first-run', '--no-default-browser-check', '--hide-scrollbars', '--mute-audio',
    '--allow-file-access-from-files', '--force-color-profile=srgb', '--force-device-scale-factor=1',
    `--window-size=${WIDTH},${HEIGHT}`, 'about:blank',
  ], { stdio: ['ignore', 'ignore', 'ignore', 'pipe', 'pipe'] });

  let nextId = 1, buffer = '';
  const pending = new Map(), listeners = [];
  proc.stdio[4].on('data', chunk => {
    buffer += chunk.toString('utf8');
    let end;
    while ((end = buffer.indexOf('\0')) >= 0) {
      const msg = JSON.parse(buffer.slice(0, end));
      buffer = buffer.slice(end + 1);
      if (msg.id && pending.has(msg.id)) {
        const { ok, ko } = pending.get(msg.id);
        pending.delete(msg.id);
        msg.error ? ko(new Error(`${msg.error.message} ${msg.error.data ?? ''}`)) : ok(msg.result);
      } else if (msg.method) {
        listeners.forEach(fn => fn(msg));
      }
    }
  });
  const send = (method, params = {}, sessionId) => new Promise((ok, ko) => {
    const id = nextId++;
    pending.set(id, { ok, ko });
    proc.stdio[3].write(JSON.stringify({ id, method, params, ...(sessionId && { sessionId }) }) + '\0');
  });
  const waitFor = (method, sessionId) => new Promise(ok => {
    const fn = msg => {
      if (msg.method === method && msg.sessionId === sessionId) { listeners.splice(listeners.indexOf(fn), 1); ok(msg.params); }
    };
    listeners.push(fn);
  });
  const exited = new Promise(ok => proc.on('exit', ok));
  const close = async () => {
    proc.kill();
    await exited;
    fs.rmSync(profile, { recursive: true, force: true, maxRetries: 5 });
  };
  return { send, waitFor, close };
}

async function openHeader(chrome) {
  const { targetId } = await chrome.send('Target.createTarget', { url: 'about:blank' });
  const { sessionId } = await chrome.send('Target.attachToTarget', { targetId, flatten: true });
  const send = (m, p) => chrome.send(m, p, sessionId);
  await send('Page.enable');
  await send('Emulation.setDeviceMetricsOverride', { width: WIDTH, height: HEIGHT, deviceScaleFactor: 1, mobile: false });
  const loaded = chrome.waitFor('Page.loadEventFired', sessionId);
  await send('Page.navigate', { url: pathToFileURL(path.join(HERE, 'header.html')).href + '?capture=1' });
  await loaded;
  const evaluate = async expression => {
    const { result, exceptionDetails } = await send('Runtime.evaluate', { expression, awaitPromise: true, returnByValue: true });
    if (exceptionDetails) throw new Error(exceptionDetails.exception?.description ?? exceptionDetails.text);
    return result.value;
  };
  await evaluate('window.ready');
  const loop = await evaluate('window.LOOP_SECONDS');
  const frameAt = async t => {
    // Two animation frames make sure the new styles are laid out and painted before the capture.
    await evaluate(`(renderAt(${t}), new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r))))`);
    const { data } = await send('Page.captureScreenshot', {
      format: 'png', clip: { x: 0, y: 0, width: WIDTH, height: HEIGHT, scale: 1 },
    });
    return Buffer.from(data, 'base64');
  };
  return { loop, frameAt };
}

// ---- Main -------------------------------------------------------------------
const chrome = launchChrome();
try {
  const page = await openHeader(chrome);

  if (opts.stills.length) {
    for (const t of opts.stills) {
      const file = path.join(HERE, `still-${t}.png`);
      fs.writeFileSync(file, await page.frameAt(t));
      console.log(`Wrote ${path.relative(process.cwd(), file)}`);
    }
  } else {
    const total = Math.min(Math.round(page.loop * opts.fps), opts.frames);
    const encoder = spawn(encoderBinary(), [opts.out, WIDTH, HEIGHT, opts.fps, opts.codec].map(String),
                          { stdio: ['pipe', 'inherit', 'inherit'] });
    const encoded = new Promise((ok, ko) => encoder.on('exit', code => code === 0 ? ok() : ko(new Error(`encoder exited with ${code}`))));
    const write = buf => encoder.stdin.write(buf) ? Promise.resolve() : new Promise(ok => encoder.stdin.once('drain', ok));
    const started = Date.now();
    for (let i = 0; i < total; i++) {
      // Frame i shows t = i / fps; the loop's last frame is one step before t = T, which equals frame 0.
      const png = await page.frameAt(i / opts.fps);
      const header = Buffer.alloc(4);
      header.writeUInt32BE(png.length);
      await write(header);
      await write(png);
      if (i % opts.fps === 0 || i === total - 1) {
        const rate = (i + 1) / ((Date.now() - started) / 1000);
        process.stdout.write(`\rFrame ${i + 1}/${total} (${rate.toFixed(1)} fps)   `);
      }
    }
    process.stdout.write('\n');
    encoder.stdin.end();
    await encoded;
  }
} finally {
  await chrome.close();
}
